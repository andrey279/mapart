"""Generate one active material for each Java 26.3 map colour."""
from pathlib import Path
import json

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def quote(value):
    return json.dumps(value, ensure_ascii=False)


rows = json.loads((HERE / "unique_materials.json").read_text())
aliases = json.loads((HERE / "removed_aliases.json").read_text())
assert len({row["selection"] for row in rows}) == len(rows)
assert len(rows) == len({row["rgb"] for row in rows}) == 60
names = {row["selection"] for row in rows}
assert not names.intersection(aliases)
assert set(aliases.values()) <= names
lines = [
    "// Code generated by verification/block_catalog/generate.py; DO NOT EDIT.",
    "package main",
    "",
    "var extraBlocks = [...]catalogBlock{",
]
for row in rows[38:]:
    props = row["properties"]
    properties = (
        "map[string]string{" + ",".join(quote(k) + ":" + quote(v) for k, v in sorted(props.items())) + "}"
        if props else "nil"
    )
    values = [
        quote(row["selection"]), quote(row["name"]), quote(row["label"]),
        quote(row["group"]), hex(row["rgb"]), properties,
        str(row["min_data_version"]), str(row["requires_support"]).lower(),
    ]
    lines.append("\t{" + ",".join(values) + "},")
lines.append("}\n")
lines.append("// Removed materials are accepted only when importing old profiles.\n// They resolve to a retained block of exactly the same Minecraft map colour.")
lines.append("var removedBlockAliases = map[string]string{")
for name, replacement in sorted(aliases.items()):
    lines.append("\t" + quote(name) + ": " + quote(replacement) + ",")
lines.append("}\n")
(ROOT / "block_catalog_generated.go").write_text("\n".join(lines))
